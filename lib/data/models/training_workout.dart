import 'exercise.dart';

class TrainingWorkout {
  const TrainingWorkout({
    required this.id,
    required this.title,
    required this.difficulty,
    required this.type,
    required this.image,
    required this.exerciseIds,
    this.targets,
    this.restSeconds,
    this.planVersion = 1,
    this.timedExercises = false,
  });
  final String id, title, image;
  final ExerciseDifficulty difficulty;
  final ExerciseType type;
  final List<String> exerciseIds;
  final List<int>? targets;
  final List<int>? restSeconds;
  final int planVersion;

  /// Some challenge days prescribe time for otherwise repetition-based moves.
  final bool timedExercises;
  String get progressStorageKey =>
      'workout_done_$id${planVersion == 1 ? '' : '_v$planVersion'}';
  int targetAt(int index) => targets?[index] ?? exercises[index].target;
  ExerciseDefinition exerciseAt(int index) {
    final base = exercises[index];
    return ExerciseDefinition(
      id: base.id,
      name: base.name,
      motion: base.motion,
      area: base.area,
      timed: base.timed,
      target: targetAt(index),
      description: base.description,
      focus: base.focus,
      difficulty: base.difficulty,
      type: base.type,
      equipment: base.equipment,
    );
  }

  int restAfter(int index) => restSeconds?[index] ?? 15;
  List<ExerciseDefinition> get exercises => [
    for (final (index, id) in exerciseIds.indexed)
      if (!timedExercises)
        exerciseById(id)
      else
        _timedExercise(exerciseById(id), targets?[index]),
  ];
  static ExerciseDefinition _timedExercise(
    ExerciseDefinition base,
    int? target,
  ) => ExerciseDefinition(
    id: base.id,
    name: base.name,
    motion: base.motion,
    area: base.area,
    timed: true,
    target: target ?? base.target,
    description: base.description,
    focus: base.focus,
    difficulty: base.difficulty,
    type: base.type,
    equipment: base.equipment,
    recommended: base.recommended,
  );
  Set<ExerciseFocus> get focus => exercises.expand((e) => e.focus).toSet();
  Set<ExerciseEquipment> get equipment =>
      exercises.expand((e) => e.equipment).toSet();
  int get estimatedMinutes {
    var seconds = 0;
    for (var i = 0; i < exerciseIds.length; i++) {
      seconds += exercises[i].timed ? targetAt(i) : targetAt(i) * 3;
      if (i < exerciseIds.length - 1) seconds += restAfter(i);
    }
    return (seconds / 60).ceil();
  }

  String get summary =>
      '~$estimatedMinutes min • ${exerciseIds.length} exercises • ${difficulty.label}';
  String get durationAndLevel => '~$estimatedMinutes min • ${difficulty.label}';
}

