  const ExerciseArea(this.label);
  final String label;
}

enum ExerciseFocus {
  abs('Abs'),
  chest('Chest'),
  back('Back'),
  arm('Arm'),
  leg('Leg'),
  glutes('Glutes'),
  shoulder('Shoulder');

  const ExerciseFocus(this.label);
  final String label;
}

enum ExerciseDifficulty {
  easy('Easy'),
  medium('Medium'),
  hard('Hard');

  const ExerciseDifficulty(this.label);
  final String label;
}

enum ExerciseType {
  warmUp('Warm up'),
  stretch('Stretch'),
  training('Training');

  const ExerciseType(this.label);
  final String label;
}

enum ExerciseEquipment {
  none('No equipment'),
  dumbbell('Dumbbell'),
  band('Band'),
  chair('Chair'),
  bench('Bench'),
  mat('Mat');

  const ExerciseEquipment(this.label);
  final String label;
}

class ExerciseDefinition {
  const ExerciseDefinition({
    required this.id,
    required this.name,
    required this.motion,
    required this.area,
    required this.timed,
    required this.target,
    required this.description,
    this.recommended = false,
    required this.focus,
    required this.difficulty,
    required this.type,
    required this.equipment,
  });
  final Set<ExerciseFocus> focus;
  final ExerciseDifficulty difficulty;
  final ExerciseType type;
  final Set<ExerciseEquipment> equipment;
  final String id;
  final String name;
  final ExerciseMotion motion;
  final ExerciseArea area;
  final bool timed;
  final int target;
  final bool recommended;
  final String description;
  Duration get animationDuration => Duration(
    milliseconds: motion == ExerciseMotion.slowClimber ? 5200 : 2600,
  );

  String targetLabel([int? value]) {
    final amount = value ?? target;
    return timed
        ? '${(amount ~/ 60).toString().padLeft(2, '0')}:${(amount % 60).toString().padLeft(2, '0')}'
        : 'x$amount';
  }
}

